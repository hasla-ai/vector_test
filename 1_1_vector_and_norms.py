# 1장 1강: 벡터, 노름,정규화(1)

## 필수1. 품질 측정 기록을 벡터로 다루기
## 필수2. 샘플별 측정값의 "크기"를 하나의 숫자로 요약하기

import numpy as np
import pandas as pd
from dataset_1_1 import get_wine_data

# 공통 난수 시드 설정
RANDOM_STATE = 42
np.random.seed(RANDOM_STATE)

def main():
    # -------------------------------------------------------------
    # [데이터 로드]
    # -------------------------------------------------------------
    X, y = get_wine_data()

    # 필수1. 품질 측정 기록을 벡터로 다루기
    ##  "측정값 묶음" 단위의 샘플 기록에 대하여, 먼저 이 기록이 스칼라·벡터·행렬 중 무엇에 해당하는지 정리함.

    # -------------------------------------------------------------
    # [문제 1-1] 스칼라·벡터·행렬 구분하기
    # -------------------------------------------------------------
    
    #1. 첫 번째 샘플의 측정값을 v1(NumPy 배열)로 추출
    v1 = X.iloc[0].to_numpy()

    #2. v1의 첫 번째 원소 추출 (스칼라)
    s1 = v1[0]

    print("=== [1장-1강-필수1] 문제 1-1 출력 결과 ===")
    print(f"1. 전체 데이터 표 (행렬, X) shape: {X.shape}")
    print(f"2. 첫 번째 샘플 (특성 벡터, v1) shape: {v1.shape}")
    print(f"3. v1의 첫 번째 원소 (스칼라, s1) 값: {s1} (특성명: {X.columns[0]})\n")

    print("=== [세 대상의 역할 구분 설명] ===")
    print("1. 데이터 행렬 (X): 전체 와인 샘플과 이화학 측정값을 통합 관리하는 2차원 공간입니다.")
    print("2. 특성 벡터 (v1): 와인 1개 샘플의 다차원 이화학 측정값 묶음으로, 데이터 공간에서 개별 와인의 위치를 정의합니다.")
    print("3. 스칼라 (s1): 산도(fixed_acidity)와 같은 단일 항목 수치로, 특성 벡터를 구성하는 개별 속성값입니다.")

    # -------------------------------------------------------------
    # [문제 1-2] 벡터의 덧셈과 스칼라 곱 계산하기
    # -------------------------------------------------------------
    # 1. 두 번째 샘플의 측정값을 v2로 추출
    v2 = X.iloc[1].to_numpy()

    # 2. 두 샘플의 평균 측정값 계산 (벡터 덧셈 + 스칼라 곱)
    v_mean = (v1 + v2) * 0.5

    # 3. v1의 각 성분을 2배로 키운 2 * v1 계산 및 원본과 비교
    v1_double = 2 * v1

    print("\n\n\n=== [1장-1강-필수1] 문제 1-2 출력 결과 ===")
    print("1. 두 샘플의 평균 벡터 (v_mean):")
    print(np.round(v_mean, 2))
    print("\n2. 스칼라 곱 결과 (2 * v1)와 원본 (v1) 비교:")
    print(f"   - 원본 v1 (상위 3개): {np.round(v1[:3], 2)}")
    print(f"   - 2 * v1  (상위 3개): {np.round(v1_double[:3], 2)}")

    print("\n=== [두 연산의 의미 설명] ===")
    print("1. 벡터 덧셈: 여러 샘플의 동일한 측정 항목들을 요소별(Element-wise)로 합산하여, "
        "데이터 합성이나 전체적인 특성 총량을 계산하는 역할을 합니다.")
    print("2. 스칼라 곱: 벡터의 방향(성분 간 비율)은 유지한 채 전체적인 크기(스케일)만 조절하여, "
        "가중치 부여나 단위 변환 및 비율 조정을 수행하는 역할을 합니다.\n")

    # 필수 2 : 샘플별 측정값의 "크기"를 하나의 숫자로 요약하기
    
    # -------------------------------------------------------------
    # [문제 2-1] L1·L2·L∞ 노름 계산하기
    # -------------------------------------------------------------
    # 1. L1, L2, L∞ 노름 계산
    l1_norm = np.linalg.norm(v1, 1)
    l2_norm = np.linalg.norm(v1, 2)
    linf_norm = np.linalg.norm(v1, np.inf)

    # 2. L2 노름 직접 계산 및 검증
    l2_direct = np.sqrt(np.sum(v1 ** 2))
    is_l2_equal = np.isclose(l2_norm, l2_direct)

    print("=== [1장-1강-필수2] 문제 2-1 출력 결과 ===")
    print(f"1. L1 노름 (L1 Norm)   : {l1_norm:.4f}")
    print(f"2. L2 노름 (L2 Norm)   : {l2_norm:.4f} (직접 계산: {l2_direct:.4f}, 일치 여부: {is_l2_equal})")
    print(f"3. L∞ 노름 (L∞ Norm)   : {linf_norm:.4f}\n")

    print("=== [세 노름의 특징 비교 설명] ===")
    print("L1 노름은 모든 성분의 절대값 합으로 전체적인 스케일의 총량을 평등하게 반영하고, "
          "L2 노름은 제곱합의 제곱근으로 기하학적 직선 거리를 반영하며, "
          "L∞ 노름은 성분 중 가장 큰 최대 절대값을 집중적으로 반영합니다.\n")

    # -------------------------------------------------------------
    # [문제 2-2] 정규화로 단위벡터 만들기
    # -------------------------------------------------------------
    # 1. v1을 L2 노름으로 나누어 단위벡터 u1 생성
    u1 = v1 / np.linalg.norm(v1, 2)
    u1_l2_norm = np.linalg.norm(u1, 2)

    print("=== [1장-1강-필수2] 문제 2-2 출력 결과 ===")
    print(f"1. 단위벡터 u1의 L2 노름: {u1_l2_norm:.4f} (1.0 일치 여부: {np.isclose(u1_l2_norm, 1.0)})\n")

    # 2. 앞 5개 샘플을 골라 정규화 전후 L2 노름 비교 표 작성
    first_5_df = X.iloc[:5]
    first_5 = first_5_df.to_numpy()

    before_norms = [np.linalg.norm(v, 2) for v in first_5]
    after_norms = [np.linalg.norm(v / np.linalg.norm(v, 2), 2) for v in first_5]

    df_comparison = pd.DataFrame({
        "샘플(ID)": first_5_df.index,
        "정규화 전 L2 노름": before_norms,
        "정규화 후 L2 노름": after_norms
    })

    print("2. 앞 5개 샘플의 정규화 전후 노름 비교 표:")
    print(df_comparison.to_string(index=False))
    print("\n=== [정규화의 의미 설명] ===")
    print("정규화는 벡터의 방향(각 성분 간 상대적 비율)을 유지하면서, 크기(L2 노름)를 항상 1로 통일하여 크기 차이에 따른 왜곡 없이 순수한 성분 조합 형태를 비교할 수 있게 합니다.\n")
    
if __name__ == "__main__":
    main()